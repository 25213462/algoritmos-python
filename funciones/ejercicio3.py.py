"""
f3
Diseña una función llamada repetir_texto(texto, veces) que
devuelva la palabra repetida la cantidad de veces indicada.
"""
# esto repite un texto varias veces, t es el texto, v es el numero de veces
def rt(t, v):
    return t * v
# 3 ejemplos
print(rt("Eco", 3))
print(rt("Hola", 1))
print(rt("Ja", 4))
